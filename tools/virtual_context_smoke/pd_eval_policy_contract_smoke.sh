#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

fail() {
  echo "[FAIL] $*" >&2
  exit 1
}

expect_eq() {
  local name="$1"
  local expected="$2"
  local actual="${!name-}"
  [[ "${actual}" == "${expected}" ]] || \
    fail "${name}: expected=${expected} actual=${actual}"
}

export VLLM_VIRTUAL_CONTEXT_RING_COMPUTE_GROUP_TOKENS=2048
export VLLM_PD_EVAL_RING_NATIVE_REDUCTION=1
export VLLM_PD_EVAL_RING_TRITON_BLOCK_M=128
export VLLM_PD_EVAL_RING_TRITON_BLOCK_N=64
export VLLM_PD_EVAL_RESIDENCY_VICTIM_POLICY=min_ring_chunks
export VLLM_PD_EVAL_RESIDENCY_RING_CHUNK_TOKENS=2048
export VLLM_PD_EVAL_SCHEDULED_PREFILL_FIT_CAPACITY_FRACTION=0.99
export VLLM_PD_EVAL_RING_MIN_PREFILL_TOKENS_WITH_DECODE=2048
source "${ROOT_DIR}/tools/pd_eval_policy_env.sh"

export VLLM_PD_EVAL_POLICY=muxwise_dynamic_virtual_ring_optimized
pd_eval_policy_apply
expect_eq VLLM_VIRTUAL_CONTEXT_RING_TRITON_FUSED_UPDATE 1
expect_eq VLLM_VIRTUAL_CONTEXT_RING_NATIVE_REDUCTION 1
expect_eq VLLM_VIRTUAL_CONTEXT_RING_TRITON_BLOCK_M 128
expect_eq VLLM_VIRTUAL_CONTEXT_RING_TRITON_BLOCK_N 64
expect_eq VLLM_VIRTUAL_CONTEXT_RING_PAGED_HBM_UPDATE 1
expect_eq VLLM_VIRTUAL_CONTEXT_RING_FULLY_OPTIMIZED_STRICT 1
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_PAGE_POOL_CONTIGUOUS 1
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_PAGE_POOL_MIRROR_DICT 0
expect_eq VLLM_VIRTUAL_CONTEXT_RING_CUDA_EVENT_TIMING 0
expect_eq VLLM_VIRTUAL_CONTEXT_RING_COMPUTE_GROUP_TOKENS 2048
expect_eq VLLM_VIRTUAL_CONTEXT_RELOAD_BULK_TOKENS 2048
expect_eq VLLM_VIRTUAL_CONTEXT_RELOAD_STAGING_SCATTER 1
expect_eq VLLM_VIRTUAL_CONTEXT_RELOAD_FUSED_SCATTER 1
expect_eq VLLM_VIRTUAL_CONTEXT_RELOAD_DIRECT_MULTICOPY 0
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_REGISTER_DIRECT_MULTICOPY 0
expect_eq VLLM_VIRTUAL_CONTEXT_DEBUG_SNAPSHOT_INTERVAL 64
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_REGISTER_PRESSURE_ONLY 1
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_REGISTER_CONTROL_DISPATCHER 1
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_REGISTER_CONTROL_DISPATCHER_WORKERS 1
expect_eq VLLM_VIRTUAL_CONTEXT_D2H_SOURCE_PLAN 1
expect_eq VLLM_VIRTUAL_CONTEXT_D2H_SOURCE_BLOCK_LEASE 1
expect_eq VLLM_VIRTUAL_CONTEXT_D2H_SOURCE_VIEW_DISPATCH 1
expect_eq VLLM_PD_PHASE_DEPTH_ENABLED 1
expect_eq VLLM_PD_PREFILL_INFLIGHT_DEPTH 1
expect_eq VLLM_PD_DECODE_INFLIGHT_DEPTH 1
expect_eq VLLM_PD_GLOBAL_INFLIGHT_DEPTH 2
expect_eq VLLM_PD_SINGLE_INFLIGHT_PER_PHASE 0
expect_eq VLLM_PD_PAIRED_PHASE_LAUNCH 0
expect_eq VLLM_PD_DECOUPLED_PAIRED_RECOVERY 0
expect_eq VLLM_PD_PHASE_SYNC_SAMPLE_OUTPUT 0

export VLLM_PD_EVAL_PREFILL_INFLIGHT_DEPTH=2
export VLLM_PD_EVAL_GLOBAL_INFLIGHT_DEPTH=3
pd_eval_policy_apply
expect_eq VLLM_PD_PREFILL_INFLIGHT_DEPTH 2
expect_eq VLLM_PD_GLOBAL_INFLIGHT_DEPTH 3
unset VLLM_PD_EVAL_PREFILL_INFLIGHT_DEPTH
unset VLLM_PD_EVAL_GLOBAL_INFLIGHT_DEPTH
pd_eval_policy_apply
expect_eq VLLM_PD_PREFILL_INFLIGHT_DEPTH 1
expect_eq VLLM_PD_GLOBAL_INFLIGHT_DEPTH 2

expect_eq VLLM_VIRTUAL_CONTEXT_PENDING_VICTIM_INTENT 1
expect_eq VLLM_VIRTUAL_CONTEXT_NATIVE_DECODE_CONTROL_FAST_PATH 1
expect_eq VLLM_VIRTUAL_CONTEXT_DELTA_HBM_OBSERVE 1
expect_eq VLLM_VIRTUAL_CONTEXT_RING_MIN_PROGRESS_TOKENS 1024
expect_eq VLLM_VIRTUAL_CONTEXT_RESIDENCY_VICTIM_POLICY min_ring_chunks
expect_eq VLLM_VIRTUAL_CONTEXT_RESIDENCY_RING_CHUNK_TOKENS 2048
expect_eq VLLM_VIRTUAL_CONTEXT_SCHEDULED_PREFILL_FIT_CAPACITY_FRACTION 0.99
expect_eq VLLM_PD_RING_MIN_PREFILL_TOKENS_WITH_DECODE 2048
expect_eq VLLM_VIRTUAL_CONTEXT_PREFILL_RING_TOKENS_WITH_DECODE_COLD 2048

# Without an explicit caller override, virtual-Ring policies preserve 2% of
# usable KV capacity for Decode growth.
(
  unset VLLM_PD_EVAL_SCHEDULED_PREFILL_FIT_CAPACITY_FRACTION
  unset VLLM_VIRTUAL_CONTEXT_SCHEDULED_PREFILL_FIT_CAPACITY_FRACTION
  unset _PD_EVAL_INPUT_SCHEDULED_PREFILL_FIT_CAPACITY_FRACTION
  source "${ROOT_DIR}/tools/pd_eval_policy_env.sh"
  export VLLM_PD_EVAL_POLICY=muxwise_dynamic_virtual_ring
  pd_eval_policy_apply
  expect_eq VLLM_VIRTUAL_CONTEXT_SCHEDULED_PREFILL_FIT_CAPACITY_FRACTION 0.98
)

# A caller that configures the canonical Ring bandwidth minimum must not fall
# back to the legacy 1K active-Decode cap when the older admission alias is
# absent.
(
  unset VLLM_PD_EVAL_RING_MIN_PREFILL_TOKENS_WITH_DECODE
  unset VLLM_PD_EVAL_RING_PREFILL_ADMISSION_TOKENS
  export VLLM_PD_EVAL_RING_BW_MIN_TOKENS=2048
  export VLLM_PD_EVAL_RING_BW_MAX_TOKENS=2048
  pd_eval_policy_apply
  expect_eq VLLM_PD_RING_MIN_PREFILL_TOKENS_WITH_DECODE 2048
  expect_eq VLLM_VIRTUAL_CONTEXT_ACTIVE_DECODE_NATIVE_PREFILL_TOKENS 2048
  expect_eq VLLM_VIRTUAL_CONTEXT_ACTIVE_DECODE_RING_PREFILL_TOKENS 2048
  expect_eq VLLM_VIRTUAL_CONTEXT_PREFILL_RING_TOKENS_WITH_DECODE_COLD 2048
)

export VLLM_PD_EVAL_RELOAD_DIRECT_MULTICOPY=1
pd_eval_policy_apply
expect_eq VLLM_VIRTUAL_CONTEXT_RELOAD_DIRECT_MULTICOPY 1
unset VLLM_PD_EVAL_RELOAD_DIRECT_MULTICOPY

export VLLM_PD_EVAL_DRAM_REGISTER_DIRECT_MULTICOPY=1
pd_eval_policy_apply
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_REGISTER_DIRECT_MULTICOPY 1
unset VLLM_PD_EVAL_DRAM_REGISTER_DIRECT_MULTICOPY

export VLLM_PD_EVAL_POLICY=muxwise_dynamic_virtual_ring
pd_eval_policy_apply
expect_eq VLLM_VIRTUAL_CONTEXT_RING_TRITON_FUSED_UPDATE 0
expect_eq VLLM_VIRTUAL_CONTEXT_RING_NATIVE_REDUCTION 1
expect_eq VLLM_VIRTUAL_CONTEXT_RING_TRITON_BLOCK_M 128
expect_eq VLLM_VIRTUAL_CONTEXT_RING_TRITON_BLOCK_N 64
expect_eq VLLM_VIRTUAL_CONTEXT_RING_PAGED_HBM_UPDATE 0
expect_eq VLLM_VIRTUAL_CONTEXT_RING_FULLY_OPTIMIZED_STRICT 0
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_PAGE_POOL_CONTIGUOUS 0
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_PAGE_POOL_MIRROR_DICT 1
expect_eq VLLM_VIRTUAL_CONTEXT_RING_CUDA_EVENT_TIMING 1
expect_eq VLLM_VIRTUAL_CONTEXT_RING_COMPUTE_GROUP_TOKENS 2048
expect_eq VLLM_VIRTUAL_CONTEXT_RELOAD_BULK_TOKENS 0
expect_eq VLLM_VIRTUAL_CONTEXT_RELOAD_STAGING_SCATTER 0
expect_eq VLLM_VIRTUAL_CONTEXT_RELOAD_FUSED_SCATTER 0
expect_eq VLLM_VIRTUAL_CONTEXT_RELOAD_DIRECT_MULTICOPY 0
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_REGISTER_DIRECT_MULTICOPY 0
expect_eq VLLM_VIRTUAL_CONTEXT_DEBUG_SNAPSHOT_INTERVAL 1
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_REGISTER_PRESSURE_ONLY 0
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_REGISTER_CONTROL_DISPATCHER 0
expect_eq VLLM_VIRTUAL_CONTEXT_D2H_SOURCE_PLAN 0
expect_eq VLLM_VIRTUAL_CONTEXT_D2H_SOURCE_BLOCK_LEASE 0
expect_eq VLLM_VIRTUAL_CONTEXT_D2H_SOURCE_VIEW_DISPATCH 0
expect_eq VLLM_PD_DECOUPLED_PAIRED_RECOVERY 0
expect_eq VLLM_VIRTUAL_CONTEXT_PENDING_VICTIM_INTENT 1
expect_eq VLLM_VIRTUAL_CONTEXT_NATIVE_DECODE_CONTROL_FAST_PATH 0
expect_eq VLLM_VIRTUAL_CONTEXT_DELTA_HBM_OBSERVE 0
expect_eq VLLM_VIRTUAL_CONTEXT_RING_MIN_PROGRESS_TOKENS 1024
expect_eq VLLM_VIRTUAL_CONTEXT_RESIDENCY_VICTIM_POLICY min_ring_chunks
expect_eq VLLM_VIRTUAL_CONTEXT_RESIDENCY_RING_CHUNK_TOKENS 2048
expect_eq VLLM_VIRTUAL_CONTEXT_SCHEDULED_PREFILL_FIT_CAPACITY_FRACTION 0.99
expect_eq VLLM_PD_RING_MIN_PREFILL_TOKENS_WITH_DECODE 2048
expect_eq VLLM_VIRTUAL_CONTEXT_PREFILL_RING_TOKENS_WITH_DECODE_COLD 2048

export VLLM_PD_EVAL_POLICY=muxwise_dynamic_virtual_chunked
pd_eval_policy_apply
expect_eq VLLM_VIRTUAL_CONTEXT_RING_BACKEND 0
expect_eq VLLM_VIRTUAL_CONTEXT_RING_ATTENTION_PLAN_TENSORS 0
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_REGISTER_ASYNC 0
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_PAGE_POOL 0
expect_eq VLLM_VIRTUAL_CONTEXT_RING_TRITON_FUSED_UPDATE 0
expect_eq VLLM_VIRTUAL_CONTEXT_RING_NATIVE_REDUCTION 0
expect_eq VLLM_VIRTUAL_CONTEXT_RING_FULLY_OPTIMIZED_STRICT 0
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_REGISTER_PRESSURE_ONLY 0
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_REGISTER_CONTROL_DISPATCHER 0
expect_eq VLLM_VIRTUAL_CONTEXT_D2H_SOURCE_PLAN 0
expect_eq VLLM_VIRTUAL_CONTEXT_D2H_SOURCE_BLOCK_LEASE 0
expect_eq VLLM_VIRTUAL_CONTEXT_D2H_SOURCE_VIEW_DISPATCH 0
expect_eq VLLM_PD_DECOUPLED_PAIRED_RECOVERY 0
expect_eq VLLM_VIRTUAL_CONTEXT_PENDING_VICTIM_INTENT 0
expect_eq VLLM_VIRTUAL_CONTEXT_NATIVE_DECODE_CONTROL_FAST_PATH 0
expect_eq VLLM_VIRTUAL_CONTEXT_DELTA_HBM_OBSERVE 0
expect_eq VLLM_VIRTUAL_CONTEXT_RING_MIN_PROGRESS_TOKENS 0
expect_eq VLLM_VIRTUAL_CONTEXT_RELOAD_BULK_TOKENS 0
expect_eq VLLM_VIRTUAL_CONTEXT_RELOAD_STAGING_SCATTER 0
expect_eq VLLM_VIRTUAL_CONTEXT_RELOAD_FUSED_SCATTER 0
expect_eq VLLM_VIRTUAL_CONTEXT_RELOAD_DIRECT_MULTICOPY 0
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_REGISTER_DIRECT_MULTICOPY 0
expect_eq VLLM_VIRTUAL_CONTEXT_DEBUG_SNAPSHOT_INTERVAL 1
expect_eq VLLM_VIRTUAL_CONTEXT_RESIDENCY_VICTIM_POLICY longest_logical_context_first
expect_eq VLLM_VIRTUAL_CONTEXT_RESIDENCY_RING_CHUNK_TOKENS 0
expect_eq VLLM_VIRTUAL_CONTEXT_SCHEDULED_PREFILL_FIT_CAPACITY_FRACTION 1.0

export VLLM_PD_EVAL_POLICY=mixed_iteration
pd_eval_policy_apply
expect_eq VLLM_VIRTUAL_CONTEXT 0
expect_eq VLLM_VIRTUAL_CONTEXT_RING_BACKEND 0
expect_eq VLLM_VIRTUAL_CONTEXT_RING_NATIVE_REDUCTION 0
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_PAGE_POOL 0
expect_eq VLLM_VIRTUAL_CONTEXT_LAYER_RELOAD_PREFETCH 0
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_REGISTER_PRESSURE_ONLY 0
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_REGISTER_CONTROL_DISPATCHER 0
expect_eq VLLM_VIRTUAL_CONTEXT_D2H_SOURCE_PLAN 0
expect_eq VLLM_VIRTUAL_CONTEXT_D2H_SOURCE_BLOCK_LEASE 0
expect_eq VLLM_VIRTUAL_CONTEXT_D2H_SOURCE_VIEW_DISPATCH 0
expect_eq VLLM_PD_DECOUPLED_PAIRED_RECOVERY 0
expect_eq VLLM_PD_PHASE_DEPTH_ENABLED 0
expect_eq VLLM_VIRTUAL_CONTEXT_NATIVE_DECODE_CONTROL_FAST_PATH 0
expect_eq VLLM_VIRTUAL_CONTEXT_DELTA_HBM_OBSERVE 0
expect_eq VLLM_VIRTUAL_CONTEXT_RING_MIN_PROGRESS_TOKENS 0
expect_eq VLLM_VIRTUAL_CONTEXT_RELOAD_BULK_TOKENS 0
expect_eq VLLM_VIRTUAL_CONTEXT_RELOAD_STAGING_SCATTER 0
expect_eq VLLM_VIRTUAL_CONTEXT_RELOAD_FUSED_SCATTER 0
expect_eq VLLM_VIRTUAL_CONTEXT_RELOAD_DIRECT_MULTICOPY 0
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_REGISTER_DIRECT_MULTICOPY 0
expect_eq VLLM_VIRTUAL_CONTEXT_DEBUG_SNAPSHOT_INTERVAL 1
expect_eq VLLM_VIRTUAL_CONTEXT_RESIDENCY_VICTIM_POLICY longest_logical_context_first
expect_eq VLLM_VIRTUAL_CONTEXT_RESIDENCY_RING_CHUNK_TOKENS 0
expect_eq VLLM_VIRTUAL_CONTEXT_SCHEDULED_PREFILL_FIT_CAPACITY_FRACTION 1.0

export VLLM_PD_EVAL_POLICY=muxwise_dynamic
pd_eval_policy_apply
expect_eq VLLM_VIRTUAL_CONTEXT 0
expect_eq VLLM_VIRTUAL_CONTEXT_RING_BACKEND 0
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_REGISTER_PRESSURE_ONLY 0
expect_eq VLLM_VIRTUAL_CONTEXT_DRAM_REGISTER_DIRECT_MULTICOPY 0
expect_eq VLLM_VIRTUAL_CONTEXT_NATIVE_DECODE_CONTROL_FAST_PATH 0
expect_eq VLLM_PD_PHASE_DEPTH_ENABLED 1
expect_eq VLLM_PD_PAIRED_PHASE_LAUNCH 0
expect_eq VLLM_PD_DECOUPLED_PAIRED_RECOVERY 0
expect_eq VLLM_PD_PHASE_SYNC_SAMPLE_OUTPUT 0
expect_eq VLLM_VIRTUAL_CONTEXT_RESIDENCY_VICTIM_POLICY longest_logical_context_first
expect_eq VLLM_VIRTUAL_CONTEXT_RESIDENCY_RING_CHUNK_TOKENS 0
expect_eq VLLM_VIRTUAL_CONTEXT_SCHEDULED_PREFILL_FIT_CAPACITY_FRACTION 1.0

export VLLM_PD_EVAL_PHASE_DEPTH_ENABLED=0
pd_eval_policy_apply
expect_eq VLLM_PD_PHASE_DEPTH_ENABLED 0
expect_eq VLLM_PD_SINGLE_INFLIGHT_PER_PHASE 1
expect_eq VLLM_PD_PAIRED_PHASE_LAUNCH 1
expect_eq VLLM_PD_DECOUPLED_PAIRED_RECOVERY 1
unset VLLM_PD_EVAL_PHASE_DEPTH_ENABLED

echo "[OK] P/D evaluation policy transitions are case-isolated"
