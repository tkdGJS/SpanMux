pd_eval_policy_enable_muxwise_lane_runtime() {
  local phase_depth_enabled
  local native_prefill_capacity_mode
  phase_depth_enabled="${VLLM_PD_EVAL_PHASE_DEPTH_ENABLED:-1}"
  native_prefill_capacity_mode="${VLLM_PD_EVAL_NATIVE_PREFILL_CAPACITY_MODE:-guard_wait}"
  export VLLM_PD_MULTIPLEXING_BASELINE=muxwise_dynamic
  export VLLM_PD_DECOUPLED_NO_MIX=1
  export VLLM_PD_INDEPENDENT_PHASE_QUEUES=1
  export VLLM_PD_SEPARATE_SCHEDULERS=1
  export VLLM_PD_DUAL_CONTINUOUS_BATCHING=1
  export VLLM_PD_NONBLOCKING_PHASE_RECOVERY=1
  export VLLM_PD_PHASE_DEPTH_ENABLED="${phase_depth_enabled}"
  export VLLM_PD_PREFILL_INFLIGHT_DEPTH="${VLLM_PD_EVAL_PREFILL_INFLIGHT_DEPTH:-1}"
  export VLLM_PD_DECODE_INFLIGHT_DEPTH="${VLLM_PD_EVAL_DECODE_INFLIGHT_DEPTH:-1}"
  export VLLM_PD_GLOBAL_INFLIGHT_DEPTH="${VLLM_PD_EVAL_GLOBAL_INFLIGHT_DEPTH:-2}"
  export VLLM_PD_MUXWISE_EVENT_LOOP=1
  if pd_eval_policy_bool_true "${phase_depth_enabled}"; then
    export VLLM_PD_SINGLE_INFLIGHT_PER_PHASE=0
    # A legacy pair exposes one shared execute future to both phases. Keep
    # independent P=1/D=1 futures so Decode completion never depends on the
    # outstanding Prefill future.
    export VLLM_PD_PAIRED_PHASE_LAUNCH=0
    export VLLM_PD_DECOUPLED_PAIRED_RECOVERY=0
  else
    export VLLM_PD_SINGLE_INFLIGHT_PER_PHASE=1
    export VLLM_PD_PAIRED_PHASE_LAUNCH=1
    export VLLM_PD_DECOUPLED_PAIRED_RECOVERY="${VLLM_PD_EVAL_DECOUPLED_PAIRED_RECOVERY:-1}"
  fi
  export VLLM_PD_PHASE_LOCAL_MODEL_RUNNER=1
  export VLLM_PD_PHASE_SYNC_SAMPLE_OUTPUT="${VLLM_PD_EVAL_PHASE_SYNC_SAMPLE_OUTPUT:-0}"
  export VLLM_PD_ASYNC_UNIPROC_EXECUTOR=1
  export VLLM_PD_ASYNC_UNIPROC_PHASE_WORKERS=1
  export VLLM_PD_ASYNC_UNIPROC_WORKERS_PER_PHASE="${VLLM_PD_ASYNC_UNIPROC_WORKERS_PER_PHASE:-1}"
  export VLLM_PD_ASYNC_UNIPROC_CONCURRENT_PHASE_SUBMIT=1
  case "${native_prefill_capacity_mode}" in
    guard_wait)
      # Admit a native Prefill beside active Decode only when its complete
      # remaining prompt KV fits, and preserve partial Prefill progress if an
      # authoritative allocation still misses capacity.
      export VLLM_PD_WAIT_ON_PREFILL_KV_CAPACITY=1
      export VLLM_PD_MUXWISE_DYNAMIC_POLICY=1
      ;;
    legacy_preempt_recompute)
      # Reproduction mode for the upstream-style recompute preemption failure
      # under experimental P/D multiplexing. Bypass the whole-Prefill guard
      # and let allocate_slots() failure reach _preempt_request(), which frees
      # KV and resets num_computed_tokens before retrying.
      export VLLM_PD_WAIT_ON_PREFILL_KV_CAPACITY=0
      export VLLM_PD_MUXWISE_DYNAMIC_POLICY=0
      ;;
    *)
      echo "[pd_eval_policy] invalid VLLM_PD_EVAL_NATIVE_PREFILL_CAPACITY_MODE='${native_prefill_capacity_mode}'; expected guard_wait or legacy_preempt_recompute" >&2
      return 2
      ;;
  esac
  export VLLM_PD_MUXWISE_DYNAMIC_PAIR_ON_BOTH_READY="${VLLM_PD_MUXWISE_DYNAMIC_PAIR_ON_BOTH_READY:-1}"
  export VLLM_PD_MUXWISE_DYNAMIC_TBT_SLO_MS="${VLLM_PD_MUXWISE_DYNAMIC_TBT_SLO_MS:-${VLLM_PD_TBT_SLO_MS:-200}}"
  export VLLM_PD_MUXWISE_DYNAMIC_PREFILL_STARVATION_MS="${VLLM_PD_MUXWISE_DYNAMIC_PREFILL_STARVATION_MS:-1000}"
  export VLLM_PD_MUXWISE_DYNAMIC_DECODE_BURST="${VLLM_PD_MUXWISE_DYNAMIC_DECODE_BURST:-4}"
  export VLLM_PD_PREFILL_STARVATION_MAX_DECODE_ITERS="${VLLM_PD_PREFILL_STARVATION_MAX_DECODE_ITERS:-256}"
  export VLLM_PD_REQUEST_FCFS="${VLLM_PD_EVAL_REQUEST_FCFS:-1}"
}

