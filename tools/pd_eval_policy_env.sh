pd_eval_policy_bool_true() {
  case "${1:-}" in
    1|true|TRUE|yes|YES|on|ON) return 0 ;;
    *) return 1 ;;
  esac
}

pd_eval_policy_normalize() {
  local raw="${1:-manual}"
  case "${raw}" in
    ""|manual|none|custom) echo "manual" ;;
    1|mixed|mixed_iteration|pd_mixed|pd_mixed_iteration) echo "mixed_iteration" ;;
    2|static|static_pd|pd_static|static_multiplexing) echo "static_pd" ;;
    static_virtual_chunked|static_pd_virtual_chunked|static_virtual_context_chunked|static_chunked) echo "static_pd_virtual_chunked" ;;
    static_virtual_ring|static_pd_virtual_ring|static_context_ring|static_ring) echo "static_pd_virtual_ring" ;;
    static_virtual_ring_optimized|static_pd_virtual_ring_optimized|static_ring_optimized) echo "static_pd_virtual_ring_optimized" ;;
    3|muxwise|muxwise_dynamic|dynamic|dynamic_pd) echo "muxwise_dynamic" ;;
    4|muxwise_virtual_chunked|muxwise_dynamic_virtual_chunked|dynamic_virtual_chunked|virtual_chunked) echo "muxwise_dynamic_virtual_chunked" ;;
    5|muxwise_virtual_ring|muxwise_dynamic_virtual_ring|dynamic_virtual_ring|context_ring) echo "muxwise_dynamic_virtual_ring" ;;
    muxwise_virtual_ring_optimized|muxwise_dynamic_virtual_ring_optimized|dynamic_virtual_ring_optimized|context_ring_optimized) echo "muxwise_dynamic_virtual_ring_optimized" ;;
    6|muxwise_virtual_ring_slo|muxwise_dynamic_virtual_ring_slo|dynamic_virtual_ring_slo|context_ring_slo|slo) echo "muxwise_dynamic_virtual_ring_slo" ;;
    muxwise_virtual_ring_optimized_slo|muxwise_dynamic_virtual_ring_optimized_slo|dynamic_virtual_ring_optimized_slo|context_ring_optimized_slo) echo "muxwise_dynamic_virtual_ring_optimized_slo" ;;
    *)
      echo "[pd_eval_policy] unknown VLLM_PD_EVAL_POLICY='${raw}'" >&2
      return 2
      ;;
  esac
}

