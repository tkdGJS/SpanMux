pd_eval_policy_apply() {
  local policy
  policy="$(pd_eval_policy_normalize "${VLLM_PD_EVAL_POLICY:-manual}")" || return $?
  export VLLM_PD_EVAL_POLICY_NORMALIZED="${policy}"

  if [[ "${policy}" == "manual" ]]; then
    export VLLM_PD_EVAL_POLICY_STATUS="manual"
    return 0
  fi

  export VLLM_PD_EVAL_POLICY_STATUS="selected"
  export VLLM_PD_EVAL_CONTEXT_MODE="none"
  export VLLM_PD_EVAL_SLO_AWARE=0
  pd_eval_policy_clear_slo

  case "${policy}" in
    mixed_iteration)
      pd_eval_policy_disable_green_pd
      pd_eval_policy_disable_phase_queues
      pd_eval_policy_clear_virtual_context
      export VLLM_ENABLE_CHUNKED_PREFILL="${VLLM_PD_EVAL_MIXED_ENABLE_CHUNKED_PREFILL:-1}"
      export VLLM_PD_EVAL_MULTIPLEXING_MODE="mixed_iteration"
      ;;
    static_pd)
      pd_eval_policy_enable_green_pd
      pd_eval_policy_enable_static_phase_separation
      pd_eval_policy_clear_virtual_context
      export VLLM_ENABLE_CHUNKED_PREFILL="${VLLM_PD_EVAL_STATIC_ENABLE_CHUNKED_PREFILL:-1}"
      export VLLM_PD_EVAL_MULTIPLEXING_MODE="static_phase_separated"
      ;;
    static_pd_virtual_chunked)
      pd_eval_policy_enable_green_pd
      pd_eval_policy_enable_static_phase_separation
      pd_eval_policy_enable_virtual_chunked
      export VLLM_PD_EVAL_CONTEXT_MODE="virtual_context_chunked_prefill"
      export VLLM_PD_EVAL_MULTIPLEXING_MODE="static_phase_separated"
      ;;
    static_pd_virtual_ring)
      pd_eval_policy_enable_green_pd
      pd_eval_policy_enable_static_phase_separation
      pd_eval_policy_enable_virtual_ring
      export VLLM_PD_EVAL_CONTEXT_MODE="virtual_context_context_ring"
      export VLLM_PD_EVAL_MULTIPLEXING_MODE="static_phase_separated"
      export VLLM_PD_EVAL_POLICY_STATUS="experimental_static_ring"
      ;;
    static_pd_virtual_ring_optimized)
      pd_eval_policy_enable_green_pd
      pd_eval_policy_enable_static_phase_separation
      pd_eval_policy_enable_virtual_ring
      pd_eval_policy_enable_fully_optimized_ring
      export VLLM_PD_EVAL_CONTEXT_MODE="virtual_context_context_ring_optimized"
      export VLLM_PD_EVAL_MULTIPLEXING_MODE="static_phase_separated"
      export VLLM_PD_EVAL_POLICY_STATUS="experimental_static_ring_optimized"
      ;;
    muxwise_dynamic)
      pd_eval_policy_enable_green_pd
      pd_eval_policy_enable_muxwise_lane_runtime
      pd_eval_policy_clear_virtual_context
      export VLLM_ENABLE_CHUNKED_PREFILL="${VLLM_PD_EVAL_DYNAMIC_ENABLE_CHUNKED_PREFILL:-1}"
      export VLLM_PD_EVAL_MULTIPLEXING_MODE="muxwise_like_dynamic_lanes"
      ;;
    muxwise_dynamic_virtual_chunked)
      pd_eval_policy_enable_green_pd
      pd_eval_policy_enable_muxwise_lane_runtime
      pd_eval_policy_enable_virtual_chunked
      export VLLM_PD_EVAL_CONTEXT_MODE="virtual_context_chunked_prefill"
