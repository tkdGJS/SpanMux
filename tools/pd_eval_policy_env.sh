# If VLLM_PD_EVAL_POLICY is unset or "manual", no low-level flags are changed.

# Preserve direct user input before a policy sweep starts mutating runtime
# variables in the current shell. Each case is then rebuilt from this value
# instead of inheriting the previous policy's generated setting.
